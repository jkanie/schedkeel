-- Job definitions (owned by the job module, audited by Envers).
CREATE TABLE jobs (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(80)   NOT NULL UNIQUE,
    description           VARCHAR(500),
    cron                  VARCHAR(120)  NOT NULL,
    time_zone             VARCHAR(64)   NOT NULL,
    type                  VARCHAR(16)   NOT NULL,
    target                VARCHAR(2000) NOT NULL,
    payload               TEXT,
    enabled               BOOLEAN       NOT NULL,
    concurrency           VARCHAR(16)   NOT NULL,
    max_retries           INT           NOT NULL,
    retry_backoff_seconds INT           NOT NULL,
    timeout_seconds       INT           NOT NULL,
    version               BIGINT        NOT NULL,
    created_at            TIMESTAMPTZ   NOT NULL,
    created_by            VARCHAR(80),
    updated_at            TIMESTAMPTZ   NOT NULL,
    updated_by            VARCHAR(80)
);

CREATE SEQUENCE revinfo_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE revinfo (
    rev      BIGINT PRIMARY KEY,
    revtstmp BIGINT NOT NULL,
    username VARCHAR(80)
);

CREATE TABLE jobs_aud (
    id                    BIGINT   NOT NULL,
    rev                   BIGINT   NOT NULL REFERENCES revinfo (rev),
    revtype               SMALLINT,
    name                  VARCHAR(80),
    description           VARCHAR(500),
    cron                  VARCHAR(120),
    time_zone             VARCHAR(64),
    type                  VARCHAR(16),
    target                VARCHAR(2000),
    payload               TEXT,
    enabled               BOOLEAN,
    concurrency           VARCHAR(16),
    max_retries           INT,
    retry_backoff_seconds INT,
    timeout_seconds       INT,
    PRIMARY KEY (id, rev)
);

-- When each job fires next (owned by the scheduling module).
CREATE TABLE job_schedule (
    job_id       BIGINT PRIMARY KEY REFERENCES jobs (id) ON DELETE CASCADE,
    cron         VARCHAR(120) NOT NULL,
    time_zone    VARCHAR(64)  NOT NULL,
    enabled      BOOLEAN      NOT NULL,
    next_fire_at TIMESTAMPTZ  NOT NULL
);

CREATE INDEX job_schedule_due ON job_schedule (next_fire_at) WHERE enabled;

-- Run history (owned by the run module). job_id has no foreign key,
-- so history outlives a deleted job.
CREATE TABLE runs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id         BIGINT      NOT NULL,
    job_name       VARCHAR(80) NOT NULL,
    status         VARCHAR(16) NOT NULL,
    trigger_source VARCHAR(16) NOT NULL,
    attempt        INT         NOT NULL,
    scheduled_for  TIMESTAMPTZ NOT NULL,
    not_before     TIMESTAMPTZ NOT NULL,
    started_at     TIMESTAMPTZ,
    finished_at    TIMESTAMPTZ,
    owner          VARCHAR(120),
    output         TEXT
);

CREATE INDEX runs_queue ON runs (not_before, id) WHERE status = 'QUEUED';
CREATE INDEX runs_by_job ON runs (job_name, id DESC);
CREATE INDEX runs_finished ON runs (finished_at) WHERE finished_at IS NOT NULL;
